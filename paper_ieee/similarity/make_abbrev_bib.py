"""Derive references_ieeeabbrv.bib from references.bib.

Only journal/booktitle strings are replaced by their standard ISO 4 / IEEE
reference-style abbreviations. Authors, titles, volumes, issues, pages, years,
DOIs and URLs are copied byte for byte. references.bib stays the master copy.
"""
from pathlib import Path
H = Path(__file__).resolve().parents[1]
MAP = {
 "Journal of Political Economy": "J. Political Econ.",
 "The Bell Journal of Economics and Management Science": "Bell J. Econ. Manage. Sci.",
 "Journal of Financial Economics": "J. Financ. Econ.",
 "The Journal of Finance": "J. Finance",
 "The Review of Financial Studies": "Rev. Financ. Stud.",
 "International Journal of Numerical Analysis and Modeling": "Int. J. Numer. Anal. Model.",
 "Journal of Computational Physics": "J. Comput. Phys.",
 "Proceedings of the National Academy of Sciences": "Proc. Natl. Acad. Sci.",
 "Engineering Analysis with Boundary Elements": "Eng. Anal. Bound. Elem.",
 "Nonlinear Dynamics": "Nonlinear Dyn.",
 "Annals of Finance": "Ann. Finance",
 "Journal of Artificial Intelligence Research": "J. Artif. Intell. Res.",
 "Journal of the American Statistical Association": "J. Am. Stat. Assoc.",
 "Advances in Neural Information Processing Systems": "Adv. Neural Inf. Process. Syst.",
 "Foundations and Trends in Machine Learning": "Found. Trends Mach. Learn.",
 "International Conference on Machine Learning (ICML 2017)": "Proc. Int. Conf. Mach. Learn. (ICML 2017)",
 "Proceedings of 3rd International Conference on Document Analysis and Recognition": "Proc. 3rd Int. Conf. Document Anal. Recognit.",
 "Machine Learning": "Mach. Learn.",
 "The Annals of Statistics": "Ann. Stat.",
 "Journal of Machine Learning Research": "J. Mach. Learn. Res.",
}
out, n = [], 0
for line in (H / "references.bib").read_text().splitlines():
    st = line.strip()
    for f in ("journal", "booktitle"):
        pre = f"{f} = {{"
        if st.startswith(pre) and st.rstrip(",").endswith("}"):
            val = st[len(pre):st.rstrip(",").rfind("}")]
            if val in MAP:
                line = line.replace("{" + val + "}", "{" + MAP[val] + "}"); n += 1
    out.append(line)
(H / "references_ieeeabbrv.bib").write_text("% GENERATED by similarity/make_abbrev_bib.py from references.bib.\n% Only journal/booktitle names abbreviated (ISO 4 / IEEE style). Edit references.bib, not this file.\n" + "\n".join(out) + "\n")
print(n, "venue names abbreviated")
