"""Write citation_audit.md from main.tex, main.aux, main.bbl and references.bib."""
import re
from pathlib import Path

H = Path(__file__).resolve().parent
tex = (H / "main.tex").read_text()
tex += "".join((H / "tables" / f).read_text() for f in ["table1_baselines.tex"])
aux = (H / "main.aux").read_text()
bbl = (H / "main.bbl").read_text()
bib = (H / "references.bib").read_text()

num = dict(re.findall(r"\\bibcite\{([^}]+)\}\{(\d+)\}", aux))
items = re.findall(r"\\bibitem\{([^}]+)\}(.*?)(?=\\bibitem|\\end\{thebibliography\})", bbl, re.S)
def clean(t):
    t = re.sub(r"\\hskip\s*1em plus 0.5em minus 0.4em\\relax", " ", t)
    t = t.replace("~", " ").replace("``", "\"").replace("''", "\"").replace("--", "-")
    t = re.sub(r"\\BIBentry\w+\{[^}]*\}|\\BIBdecl\w*|\\newblock|\\url|\\bibitem", "", t)
    t = re.sub(r"\\emph\{([^}]*)\}", r"\1", t)
    t = re.sub(r"[{}]|\\[a-zA-Z]+\s?", "", t)
    t = re.sub(r"1em\s+plus 0.5em minus 0.4em", " ", t)
    for a, b in [("\\`e", "è"), ('\\"o', "ö"), ("\\'E", "É"), ("\\'a", "á"), ("\\'i", "í"), ("\\'e", "é")]:
        t = t.replace(a, b)
    return " ".join(t.split())
ref = {k: clean(v) for k, v in items}

# where cited: split main.tex into sections; table1 is inside Experiments
where = {}
sec = "Front matter"
body = (H / "main.tex").read_text()
for line in body.splitlines():
    m = re.match(r"\\section\*?\{([^}]+)\}", line)
    if m:
        sec = m.group(1)
    if "\\begin{abstract}" in line:
        sec = "Abstract"
    if "tabinput{tables/table1_baselines" in line:
        for k in re.findall(r"\\cite\{([^}]+)\}", (H / "tables" / "table1_baselines.tex").read_text()):
            for kk in k.split(","):
                where.setdefault(kk.strip(), []).append("Experiments (Table I)")
    for k in re.findall(r"\\cite\{([^}]+)\}", line):
        for kk in k.split(","):
            where.setdefault(kk.strip(), []).append(sec)

bibkeys = re.findall(r"^@\w+\{([^,]+),", bib, re.M)
cited = set(where)
rows = sorted(num.items(), key=lambda x: int(x[1]))
out = ["# Citation audit", "", "Generated by `make_citation_audit.py` from the compiled `main.aux` / `main.bbl`. Numbering is IEEE order of first citation.", "",
       "| [n] | Bib key | Reference (as printed) | Sections where cited |", "|---|---|---|---|"]
for k, n in rows:
    secs = ", ".join(dict.fromkeys(where.get(k, [])))
    out.append(f"| [{n}] | {k} | {ref.get(k, 'MISSING IN BBL')} | {secs} |")
missing = sorted(cited - set(bibkeys))
unused_in_pdf = sorted(set(num) - cited)
not_cited = sorted(set(bibkeys) - cited)
etal = [k for k, v in ref.items() if "et al" in v]
out += ["", "## Checks", "",
        f"- References in compiled list: {len(num)}. Distinct keys cited in the text: {len(cited)}.",
        f"- Cited but missing from references.bib: {missing or 'none'}.",
        f"- In compiled list but never cited: {unused_in_pdf or 'none'}.",
        f"- 'et al.' in the printed reference list: {etal or 'none'}.",
        f"- In references.bib but deliberately not cited (so not printed): {not_cited or 'none'}.",
        "  - mcclenny2023self: the reported N2 runs use the 'fixed' weighting, not self-adaptive weights, so it is not cited.",
        "  - albrecher2007little: no Heston result is reported in this paper.",
        "- No equation or theorem number is attributed to any cited work.",
        "- Each cited work is used only for the claim listed in references_verification.md."]
(H / "citation_audit.md").write_text("\n".join(out) + "\n")
print("\n".join(out[-12:]))
